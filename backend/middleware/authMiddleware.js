const jwt = require('jsonwebtoken');

// Ye check karta hai ki user login hai ya nahi
const protect = (req, res, next) => {
  const authHeader = req.headers.authorization;
  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    return res.status(401).json({ message: 'Login zaroori hai' });
  }
  const token = authHeader.split(' ')[1];
  try {
    const decoded = jwt.verify(token, process.env.JWT_SECRET);
    req.user = decoded;
    next();
  } catch (err) {
    res.status(401).json({ message: 'Token invalid hai' });
  }
};

// Ye check karta hai ki user admin hai ya nahi
const adminOnly = (req, res, next) => {
  if (req.user && req.user.role === 'admin') {
    next();
  } else {
    res.status(403).json({ message: 'Sirf admin ke liye' });
  }
};

module.exports = { protect, adminOnly };
